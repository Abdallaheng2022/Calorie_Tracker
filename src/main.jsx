import { StrictMode } from 'react'
import { createRoot } from 'react-dom/client'
import './index.css'
import App from './App.jsx'
import Modal from "react-modal";

/**
 * 
 * بكل بساطة: هذا السطر يقول للمكتبة "محتوى موقعي الأساسي موجود هنا".

تخيّل أن موقعك غرفة، والنافذة المنبثقة (Modal) شخص دخل ليتكلم معك. عندما يتكلم، من الأدب أن تُطفئ التلفاز الذي خلفه حتى تركّز معه فقط.

المكتبة تفعل الشيء نفسه: عند فتح النافذة المنبثقة، "تُخفي" باقي الموقع عن برامج قراءة الشاشة التي يستخدمها المكفوفون، حتى لا يختلط عليهم الكلام. ولكي تعرف ماذا تُخفي، تحتاج أن تخبرها أين محتوى موقعك، وهذا ما يفعله السطر: #root هو مكان موقعك.

الخلاصة: اكتب السطر مرة واحدة في أعلى الكود، ولن تحتاج التفكير فيه بعد ذلك. وإذا نسيته، سيعمل كل شيء لكن ستظهر لك رسالة تحذير.
 * 
 */
Modal.setAppElement("#root");
createRoot(document.getElementById('root')).render(
  <StrictMode>
    <App />
  </StrictMode>
)
